const DAY_MS = 86400000

/**
 * Pure SM-2 spaced-repetition update function.
 */
export function reviewCardSM2(
  prev: FlashcardProgressRecord | undefined,
  quality: 0 | 3 | 4 | 5,
  now = Date.now(),
): FlashcardProgressRecord {
  const prevReps = prev?.reps ?? 0
  const prevInterval = prev?.intervalDays ?? 0
  const prevEase = prev?.ease ?? 2.5

  if (quality < 3) {
    const ease = Math.max(1.3, Number((prevEase - 0.2).toFixed(2)))
    const intervalDays = 1
    return {
      reps: 0,
      intervalDays,
      ease,
      dueAt: now + intervalDays * DAY_MS,
      lastAt: now,
    }
  }

  const reps = prevReps + 1
  const delta = 0.1 - (5 - quality) * (0.08 + (5 - quality) * 0.02)
  const ease = Math.max(1.3, Number((prevEase + delta).toFixed(2)))
  const intervalDays = reps === 1 ? 1 : reps === 2 ? 6 : Math.round(prevInterval * ease)

  return {
    reps,
    intervalDays,
    ease,
    dueAt: now + intervalDays * DAY_MS,
    lastAt: now,
  }
}

/**
 * Returns flashcards in the selected deck that are due (`!rec || rec.dueAt <= now`),
 * ordered with overdue reviewed cards first (earliest `dueAt` first), followed by unseen cards.
 */
export function getDueFlashcards(
  progressMap: Record<string, FlashcardProgressRecord>,
  deck: FlashcardDeckId | 'all',
  now = Date.now(),
): FlashcardDef[] {
  const filtered = deck === 'all' ? FLASHCARDS : FLASHCARDS.filter((card) => card.deck === deck)
  const overdue: { card: FlashcardDef; dueAt: number }[] = []
  const unseen: FlashcardDef[] = []

  for (const card of filtered) {
    const rec = progressMap[card.id]
    if (!rec) {
      unseen.push(card)
    } else if (rec.dueAt <= now) {
      overdue.push({ card, dueAt: rec.dueAt })
    }
  }

  overdue.sort((a, b) => a.dueAt - b.dueAt)
  return [...overdue.map((entry) => entry.card), ...unseen]
}
