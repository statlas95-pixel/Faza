/** Возвращает детерминированный микро-кейс для указанной даты (или со смещением offset). */
export function getDailyCase(date = new Date(), offset = 0): DailyCase {
  const dayIndex = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000)
  const idx = ((dayIndex + offset) % DAILY_CASES.length + DAILY_CASES.length) % DAILY_CASES.length
  return DAILY_CASES[idx]
}
