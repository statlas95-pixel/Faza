/** Формирует билет из 5 вопросов, соответствующих целевому грейду `targetLevel` (1..5). */
export function getExamQuestionsForGrade(targetLevel: number): GradeExamQuestion[] {
  const lvl = Math.max(1, Math.min(5, targetLevel))
  // Для высоких грейдов берём сложные вопросы + ядро, для начальных — базовые и прикладные
  const sorted = [...GRADE_EXAM_BANK].sort((a, b) => {
    const distA = Math.abs(a.minLevel - lvl)
    const distB = Math.abs(b.minLevel - lvl)
    return distA - distB
  })
  return sorted.slice(0, 5)
}

export function evaluateGradeExam(
  questions: GradeExamQuestion[],
  answers: Record<string, string>,
): { passed: boolean; score: number; correctCount: number; total: number } {
  const total = questions.length
  let correctCount = 0
  for (const q of questions) {
    const opt = q.options.find((o) => o.id === answers[q.id])
    if (opt?.correct) correctCount += 1
  }
  const score = total ? Number((correctCount / total).toFixed(2)) : 0
  return { passed: score >= 0.8, score, correctCount, total }
}
